export type TKey = keyof typeof en;
const dicts: Record<'en' | 'ru', typeof en> = { en, ru };

export function t(key: TKey, params?: Record<string, string | number>): string;
/** `optional` returns undefined instead of the key itself - used for "short label if there is one" lookups */
export function t(key: TKey, params: Record<string, string | number> | undefined, optional: true): string | undefined;
export function t(key: TKey, params?: Record<string, string | number>, optional?: true): string | undefined {
  const lang = getSettings().lang;
  const raw = dicts[lang][key] ?? en[key];
  if (raw === undefined && optional) return undefined;
  let s: string = raw ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Re-renders the component when language changes. */
export function useT(): typeof t {
  const [, force] = useState(0);
  useEffect(() => subscribeSettings(() => force((n) => n + 1)), []);
  return t;
}

